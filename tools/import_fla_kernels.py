#!/usr/bin/env python3
"""Archive every launch-referenced kernel from an existing FLA extraction.

Only source/AST inspection is performed. This tool never imports Torch or Triton,
generates tensors, launches a device, or converts archive entries into benchmarks.
Rebuilding archives preserves existing generated benchmarks and their catalog rows;
hand-written benchmark adapters are not regenerated by this importer.
"""
from __future__ import annotations

import argparse
import ast
from collections import Counter, defaultdict
import hashlib
import json
from pathlib import Path
import re
import shutil


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def inside(root: Path, relative: str) -> Path:
    path = (root / relative).resolve()
    if not path.is_relative_to(root.resolve()) or path == root.resolve():
        raise ValueError(f"Source must be a file inside its root: {relative}")
    return path


def jit_definitions(path: Path):
    return [node for node in ast.walk(ast.parse(path.read_text(encoding="utf-8")))
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
            and any("triton.jit" in ast.unparse(d) for d in node.decorator_list)]


def ast_digest(node) -> str:
    return digest(ast.dump(node, include_attributes=False).encode())


def function_text(path: Path, node) -> str:
    lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
    first = min([node.lineno] + [d.lineno for d in node.decorator_list])
    return "".join(lines[first - 1:node.end_lineno])


def public_snapshot(data: bytes):
    """Remove historical personal paths from comments, preserving the full AST."""
    text = data.decode('utf-8')
    lines, changes = [], []
    for number, line in enumerate(text.splitlines(keepends=True), 1):
        if line.lstrip().startswith('#') and '/home/' in line:
            replacement = re.sub(r'/home/\S+/flash-linear-attention/', '', line)
            if '/home/' in replacement:
                raise ValueError('Unrecognized personal path in source comment')
            changes.append({'line': number, 'change': 'Replace the personal absolute checkout prefix in an extraction provenance comment with the repository-relative path.'})
            line = replacement
        lines.append(line)
    result = ''.join(lines)
    if ast.dump(ast.parse(text), include_attributes=False) != ast.dump(ast.parse(result), include_attributes=False):
        raise AssertionError('Snapshot sanitization changed the source AST')
    return result.encode('utf-8'), changes


def classify(candidate, cases):
    groups = sorted({cases[cid]["group"] for cid in candidate["associated_tests"]})
    if len(groups) == 1:
        return groups[0]
    return "cv_vv"


def family_for(source: str, symbol: str) -> str:
    parts = Path(source).parts
    if parts[:2] == ('fla', 'ops'):
        suffix = parts[2] if parts[2] != 'utils' else 'utils/' + Path(source).stem
    elif parts[:2] == ('fla', 'modules'):
        suffix = 'modules/' + parts[2].removesuffix('.py')
        if parts[2] == 'activations.py':
            suffix = 'activations/' + re.split(r'_(?:fwd|bwd|fwdbwd)(?:_|$)', symbol)[0].strip('_')
    else:
        suffix = 'test_kernels/' + re.sub(r'_(?:fwd|bwd|fwdbwd|forward|backward)(?=_|$)', '', symbol).removesuffix('_kernel').strip('_')
    return 'flash_linear_attention/' + suffix


def build(args):
    source_root, repo = args.source_root.resolve(), args.destination.resolve()
    bundle = args.bundle.resolve() if args.bundle else None
    group = repo / "operators/flash_linear_attention"
    if bundle:
        inventory = load(bundle / "inventory/kernel_inventory.json")
        extracted = load(bundle / "extracted/manifest.json")
        all_cases = {c["id"]: c for c in load(bundle / "cases.json")}
        prepared_imports = {}
    else:
        public_input = load(args.import_manifest or (group / 'import-manifest.json'))
        inventory = public_input['inventory']
        all_cases = {c['id']: c for c in public_input['test_cases']}
        extracted = {'source_commit': inventory['source_commit'], 'cases': []}
        prepared_imports = {e['key']: e for e in public_input['extraction_records']}
    candidates = sorted((d for d in inventory["kernel_definitions"] if d["static_launch_references"]),
                        key=lambda d: (d["source"], d["line"], d["kernel"]))
    if not candidates:
        raise ValueError("The extraction inventory contains no launch candidates")
    revision = inventory["source_commit"]
    if extracted["source_commit"] != revision:
        raise ValueError("Inventory and extraction commit differ")
    names = Counter(c["kernel"] for c in candidates)
    group.mkdir(parents=True, exist_ok=True)
    prior_catalog = load(repo / 'catalog.json')
    prior_catalog_by_id = {entry['id']: entry for entry in prior_catalog['operators']}
    license_bytes = (source_root / "LICENSE").read_bytes()
    (group / "LICENSE").write_bytes(license_bytes)
    closures_by_source = defaultdict(list)
    for case in extracted["cases"]:
        for module in case.get("modules", []):
            closures_by_source[module["source"]].append((case, module))
    records, entries, extraction_records = [], [], []
    ast_groups = defaultdict(list)
    canonical_ast_sources = {}
    for original_module in sorted((source_root / 'fla').rglob('*.py')):
        for original_function in jit_definitions(original_module):
            canonical_ast_sources.setdefault(ast_digest(original_function), str(original_module.relative_to(source_root)))
    for index, candidate in enumerate(candidates, 1):
        symbol, source = candidate["kernel"], candidate["source"]
        source_path = inside(source_root, source)
        source_bytes = source_path.read_bytes()
        if digest(source_bytes) != candidate["original_source_sha256"]:
            raise ValueError(f"Original source differs from the frozen extraction: {source}")
        node = next(n for n in jit_definitions(source_path) if n.name == symbol and n.lineno == candidate["line"])
        original_ast_sha = ast_digest(node)
        family = family_for(canonical_ast_sources.get(original_ast_sha, source), symbol)
        if bundle:
            closure_options = []
            for case, module in closures_by_source[source]:
                extracted_path = inside(bundle, f"extracted/cases/{case['case_id']}/{module['extracted_file']}")
                if any(n.name == symbol and ast_digest(n) == original_ast_sha for n in jit_definitions(extracted_path)):
                    closure_options.append((len(case["modules"]), case["case_id"], case, module, extracted_path))
            if not closure_options:
                raise ValueError(f"No exact existing extraction for {candidate['key']}")
            _, _, closure, extraction_module, extracted_path = min(closure_options, key=lambda x: x[:2])
            extraction_record = {'key': candidate['key'], 'ast_sha256': original_ast_sha,
                'extraction_file': str(extracted_path.relative_to(bundle)),
                'extraction_sha256': digest(extracted_path.read_bytes()),
                'root_module': extraction_module['module'], 'closure_modules': closure['modules']}
        else:
            extraction_record = prepared_imports[candidate['key']]
            if extraction_record['ast_sha256'] != original_ast_sha:
                raise ValueError(f"Source AST differs from the public extraction inventory: {candidate['key']}")
        extraction_records.append(extraction_record)
        name = symbol if names[symbol] == 1 else f"{symbol}__{digest(source.encode())[:8]}"
        operator_id = f"FLA{index:03d}"
        ast_groups[original_ast_sha].append(operator_id)
        directory = group / name
        if directory.exists():
            if not (directory / 'operator.json').is_file():
                raise FileExistsError(f'Refusing to replace a directory without operator metadata: {directory.name}')
            existing = load(directory / "operator.json")
            if (existing.get('id') != operator_id or existing.get('runner') != 'fla'
                    or existing.get('source', {}).get('path') != source
                    or existing.get('source', {}).get('revision') != revision):
                raise ValueError(f'Refusing to replace another operator: {directory.name}')
            if existing.get("entry_mode") == "generated_benchmark":
                # Do not overwrite a reviewed executable adapter when rebuilding archives.
                records.append(existing)
                if operator_id in prior_catalog_by_id:
                    entries.append(prior_catalog_by_id[operator_id])
                else:
                    entries.append({k: existing[k] for k in ("id", "name", "family", "direction", "type", "runner", "entry_mode")})
                    entries[-1].update(path=str(directory.relative_to(repo)), implementation=existing.get('implementation', 'generated_benchmark'), validation=existing.get("validation", "NOT_DEVICE_VALIDATED"))
                continue
            if existing.get('entry_mode') != 'source_archive':
                raise ValueError(f'Refusing to replace an unknown entry mode: {directory.name}')
            if not args.replace_archives:
                raise FileExistsError(f"Archive exists; use --replace-archives: {directory.name}")
        upstream = directory / "upstream"
        if upstream.exists() and args.replace_archives:
            shutil.rmtree(upstream)
        upstream.mkdir(parents=True, exist_ok=True)
        snapshot = upstream / source_path.name
        snapshot_bytes, snapshot_changes = public_snapshot(source_bytes)
        snapshot.write_bytes(snapshot_bytes)
        (upstream / "LICENSE").write_bytes(license_bytes)
        dependencies = []
        module_index = {m['module']: m for m in extraction_record['closure_modules']}
        needed = set()
        pending = [extraction_record['root_module']]
        while pending:
            module_name = pending.pop()
            if module_name in needed:
                continue
            needed.add(module_name)
            pending.extend(module_index[module_name]['dependencies'])
        for module in sorted((module_index[name] for name in needed), key=lambda m: m["source"]):
            dependency = inside(source_root, module["source"])
            data = dependency.read_bytes()
            if digest(data) != module["source_sha256"]:
                raise ValueError(f"Dependency differs from extraction: {module['source']}")
            if module["source"] == source:
                continue
            target = upstream / "dependencies" / module["source"]
            target.parent.mkdir(parents=True, exist_ok=True)
            public_data, dependency_changes = public_snapshot(data)
            target.write_bytes(public_data)
            dependencies.append({"path": str(target.relative_to(directory)), "source": module["source"],
                                 "sha256": digest(public_data), 'original_sha256': digest(data),
                                 'snapshot_changes': dependency_changes, "extracted_module": module["module"]})
        header = (
            '# Copyright (c) 2023-2026 Songlin Yang, Yu Zhang, Zhiyuan Li\n'
            '# SPDX-License-Identifier: MIT\n'
            f'# Source: {source}:{node.lineno} at {revision}\n'
            '# Source archive: dependencies and launch adaptation are not executable here.\n'
            '# The complete original file and dependency snapshots are under upstream/.\n'
            'import triton\nimport triton.language as tl\n\n\n'
        )
        kernel_text = header + function_text(source_path, node)
        kernel_file = directory / "kernels.py"
        kernel_file.write_text(kernel_text, encoding="utf-8")
        actual_node = next(n for n in jit_definitions(kernel_file) if n.name == symbol)
        if ast_digest(actual_node) != original_ast_sha:
            raise AssertionError(f"Kernel AST changed during extraction: {candidate['key']}")
        associations = [{"id": cid, "nodeid": all_cases[cid]["original_nodeid"]} for cid in candidate["associated_tests"]]
        direction = "bwd" if "bwd" in symbol else "fwd" if "fwd" in symbol else "other"
        reason = "The original kernel and dependency sources are archived; an independently checked, self-generated benchmark launch is not yet registered."
        metadata = {
            "schema_version": 1, "id": operator_id, "name": name,
            "family": family, "direction": direction, "type": classify(candidate, all_cases),
            "runner": "fla", "entry_mode": "source_archive", "kernel_symbol": symbol,
            "baseline_id": "baseline", "adaptation_status": "blocked_adaptation", "adaptation_reason": reason,
            "implementation": "original_kernel_source_archive", "validation": "SOURCE_AST_VERIFIED",
            "source": {"repository": args.source_repository, "revision": revision, "path": source,
                       "snapshot": str(snapshot.relative_to(directory)), "sha256": digest(snapshot_bytes),
                       'original_sha256': digest(source_bytes), 'snapshot_changes': snapshot_changes,
                       "symbol": symbol, "license": "MIT", "definition_origin": candidate["definition_origin"]},
            "extraction": {"path": "kernels.py", "sha256": digest(kernel_file.read_bytes()),
                           "ast_preserved": True, "ast_sha256": original_ast_sha,
                           "existing_extraction_file": extraction_record['extraction_file'],
                           "existing_extraction_sha256": extraction_record['extraction_sha256'],
                           "changes": ["Retain the selected JIT function and all its decorators unchanged; add an archive header and common Triton imports.",
                                       "Keep full original source and dependency snapshots; do not import archive entries from the benchmark runner."]},
            "dependencies": dependencies, "original_test_cases": associations,
            "static_launch_references": candidate["static_launch_references"],
            "counting_note": "One source path and symbol; static launch references do not prove a runtime launch. JIT helpers are not separate entries.",
        }
        write_json(directory / "operator.json", metadata)
        write_json(directory / "cases.json", {"schema_version": 1, "operator": operator_id, "cases": [],
                                               "external_input_required": False,
                                               "note": "No executable benchmark is registered for this source archive."})
        (directory / "baseline.py").write_text(
            '"""Baseline source policy for this non-executable archive entry."""\n'
            f'KERNEL_SYMBOL = {symbol!r}\nSOURCE_PATH = {source!r}\n'
            'PRESERVE_ORIGINAL_TILE_GRID_AND_COMPILE_OPTIONS = True\n'
            'BENCHMARK_REGISTERED = False\n', encoding="utf-8")
        (directory / "launch.py").write_text(
            '"""Static launch locations only; no executable launch adapter is registered."""\n'
            f'STATIC_LAUNCH_REFERENCES = {tuple(candidate["static_launch_references"])!r}\n', encoding="utf-8")
        (directory / "README.md").write_text(
            f'# {operator_id}: `{symbol}`\n\n'
            f'Source archive from `{source}` at `{revision}`. '
            f'Origin: `{candidate["definition_origin"]}`. The original kernel, including its decorators, is unchanged.\n\n'
            '**Status: source archive; no executable benchmark or device validation is claimed.** '
            + reason + '\n\n'
            '`kernels.py` contains the selected function. `upstream/` contains the complete source, '
            'dependency snapshots and MIT license. Absolute data paths in upstream files are historical source text; '
            'personal checkout prefixes in provenance comments are removed when listed in `source.snapshot_changes`; '
            '`source.original_sha256` records original bytes and `source.sha256` records the published snapshot. '
            'the runner never imports or executes these archived files. `cases.json` stays empty until a '
            'self-generated input and independent reference are adapted.\n\n'
            'Original test associations:\n\n' + ''.join(f'- `{a["nodeid"]}`\n' for a in associations), encoding="utf-8")
        entries.append({"id": operator_id, "name": name, "family": family, "direction": direction,
                        "type": metadata["type"], "path": str(directory.relative_to(repo)),
                        "implementation": metadata["implementation"], "runner": "fla", "entry_mode": "source_archive",
                        "validation": "SOURCE_AST_VERIFIED"})
        records.append(metadata)
    write_json(group / "source-manifest.json", {"schema_version": 1,
               "snapshot_kind": "Import-time source archive metadata. Current executable adaptation status is authoritative in each operator.json.",
               "source_repository": args.source_repository,
               "source_revision": revision, "license_sha256": digest(license_bytes), "operators": records})
    write_json(group / 'import-manifest.json', {'schema_version': 1,
        'input_contract': 'Public static extraction inventory. Rebuild needs only this manifest and the fixed source checkout. Extraction file hashes retain prior extraction provenance; source hashes and kernel ASTs are revalidated on every import.',
        'inventory': {'source_commit': revision, 'kernel_definitions': inventory['kernel_definitions']},
        'test_cases': [{k: c[k] for k in ('id', 'group', 'original_nodeid')} for c in all_cases.values()],
        'extraction_records': extraction_records})
    write_json(group / "scope.json", {"schema_version": 1, "source_repository": args.source_repository,
               "source_revision": revision, "original_test_definitions": len(all_cases),
               "original_cv_test_definitions": sum(c["group"] == "cv" for c in all_cases.values()),
               "original_vv_test_definitions": sum(c["group"] == "vv" for c in all_cases.values()),
               "static_jit_definitions": len(inventory["kernel_definitions"]),
               "launch_referenced_operator_entries": len(entries),
               "jit_definitions_without_static_launch_reference": len(inventory["kernel_definitions"]) - len(entries),
               "definition_origins": dict(Counter(c["definition_origin"] for c in candidates)),
               "identical_ast_candidate_groups": [v for v in ast_groups.values() if len(v) > 1],
               "counting_rule": "Every statically launch-referenced source-path plus symbol is retained, regardless of timing or compilation outcome. Helpers are dependencies, not separate operators.",
               "device_execution_by_importer": False})
    (group / "catalog-table.md").write_text(
        '# FLA extracted kernel catalog\n\n'
        'These entries cover the complete static launch candidate inventory; source archives are not executable benchmarks. '
        'The live `operator.json` in each directory is authoritative for adaptation status.\n\n'
        '| ID | Kernel | Origin | Source | Entry mode |\n| --- | --- | --- | --- | --- |\n' + ''.join(
            f'| {r["id"]} | [{r["kernel_symbol"]}]({r["name"]}/) | {r["source"]["definition_origin"]} | `{r["source"]["path"]}` | {r["entry_mode"]} |\n'
            for r in records), encoding="utf-8")
    catalog_path = repo / "catalog.json"
    catalog = load(catalog_path)
    catalog["operators"] = [e for e in catalog["operators"] if e.get("runner") != "fla"] + entries
    write_json(catalog_path, catalog)
    print(json.dumps({"operators": len(entries), "original_test_definitions": len(all_cases), "device_execution": False}))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", type=Path, required=True)
    parser.add_argument("--bundle", type=Path, help='Optional original extraction bundle to regenerate the public import manifest')
    parser.add_argument('--import-manifest', type=Path, help='Public manifest; defaults to the checked-in FLA import-manifest.json')
    parser.add_argument("--destination", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--source-repository", default="https://gitcode.com/TritonAscendTest/flash-linear-attention.git")
    parser.add_argument("--replace-archives", action="store_true", help="Rebuild existing source archives; never overwrite generated benchmarks")
    build(parser.parse_args())


if __name__ == "__main__":
    main()
